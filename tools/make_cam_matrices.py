"""Generate src/cammatrix.js: colour matrices for cameras the bundled LibRaw does not know.

LibRaw renders a camera it has no matrix for in raw camera RGB (rgb_cam = identity): washed out, skin turns grey-green.
rawspeed (darktable) keeps Adobe-style XYZ->camera matrices for newer bodies. This script takes those whose model name
does not appear in the LibRaw wasm; the worker only uses an entry when LibRaw itself reports no matrix (cam_xyz all 0).

usage: python tools/make_cam_matrices.py <rawspeed data/cameras.xml> [src/vendor/libraw.wasm]
cameras.xml: https://github.com/darktable-org/rawspeed/blob/develop/data/cameras.xml (LGPL-2.1; the matrices themselves
are the Adobe DNG Converter ColorMatrix values, as also used by dcraw / LibRaw).
"""
import re, sys, json, xml.etree.ElementTree as ET

xml_path = sys.argv[1]
wasm = open(sys.argv[2] if len(sys.argv) > 2 else 'src/vendor/libraw.wasm', 'rb').read()
key = lambda make, model: (make.strip().lower() + '|' + re.sub(r'\s+', '', model).lower())

out = {}
for cam in ET.parse(xml_path).getroot().iter('Camera'):
    cm = cam.find('ColorMatrices/ColorMatrix')
    if cm is None:
        continue
    rows = [r.text.split() for r in sorted(cm.findall('ColorMatrixRow'), key=lambda r: int(r.get('plane')))]
    if len(rows) != 3 or any(len(r) != 3 for r in rows):
        continue
    m = [int(v) for r in rows for v in r]
    ids = cam.findall('ID') or []
    names = [(i.get('make'), i.get('model')) for i in ids if i.get('make') and i.get('model')]
    for alias in cam.findall('Aliases/Alias'):
        if alias.get('id'):
            names.append((ids[0].get('make') if ids else cam.get('make'), alias.get('id')))
    for make, model in names:
        # skip bodies LibRaw already lists (its table matches by model prefix, so this is only a size filter)
        if model.encode() in wasm or model.replace(' ', '').encode() in wasm:
            continue
        out[key(make, model)] = m

body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v)}' for k, v in sorted(out.items()))
open('src/cammatrix.js', 'w', encoding='utf-8', newline='\n').write(
    '// Generated by tools/make_cam_matrices.py from rawspeed data/cameras.xml (darktable): Adobe-style XYZ->camera colour\n'
    '// matrices (x10000, D65) for cameras the bundled LibRaw has no matrix for. Key: "make|model" lower case, no spaces.\n'
    'const EXTRA_CAM_XYZ = {\n' + body + '\n};\n')
print(len(out), 'cameras')
