"""Generate src/lensfun.js: lens distortion / TCA / vignetting calibrations from the lensfun database.

Nikon NEF (and Canon CR2/CR3, Pentax, Panasonic ...) carry no usable lens-correction coefficients, so darktable and
RawTherapee use lensfun; this does the same. Only rectilinear lenses; distortion ptlens and poly3 (poly5 has 5 entries in
the whole database and is skipped), TCA poly3 / linear, vignetting pa (the calibration at the largest focus distance for
each focal length and aperture). Cameras are kept for their crop factor and, for fixed-lens compacts, their lens mount.

usage: python -I tools/make_lensfun.py <dir with lensfun data/db/*.xml> [commit]
data: https://github.com/lensfun/lensfun/tree/master/data/db  (CC BY-SA 3.0; so is the generated src/lensfun.js)
"""
import base64, glob, json, os, sys, zlib, xml.etree.ElementTree as ET

db_dir = sys.argv[1]
commit = sys.argv[2] if len(sys.argv) > 2 else ''

def num(v):
    v = str(v).strip()
    x = float(v.split(':')[0]) / float(v.split(':')[1]) if ':' in v else float(v)  # aspect ratio may be "4:3"
    return 0 if x == 0 else float(f'{x:.5g}')

def names(el, tag):
    out = []
    for m in el.findall(tag):
        if m.get('lang') in (None, 'en') and m.text and m.text.strip() not in out:
            out.append(m.text.strip())
    return out

mounts_defined, lenses, cams = set(), [], []
for path in sorted(glob.glob(os.path.join(db_dir, '*.xml'))):
    root = ET.parse(path).getroot()
    for m in root.findall('mount'):
        n = m.findtext('name')
        if n:
            mounts_defined.add(n.strip())
    for c in root.findall('camera'):
        mk, md, mt = names(c, 'maker'), names(c, 'model'), c.findtext('mount')
        if not mk or not md or not mt:
            continue
        cams.append([mk[0], md, mt.strip(), num(c.findtext('cropfactor') or 1)])
    for l in root.findall('lens'):
        if (l.findtext('type') or 'rectilinear').strip() != 'rectilinear':
            continue
        mk, md = names(l, 'maker'), names(l, 'model')
        cal = l.find('calibration')
        if not mk or not md or cal is None:
            continue
        D, T, V = [], [], {}
        for d in cal.findall('distortion'):
            f, m = num(d.get('focal')), d.get('model')
            if m == 'ptlens':
                D.append([f, num(d.get('a', 0)), num(d.get('b', 0)), num(d.get('c', 0))])
            elif m == 'poly3':
                D.append([f, 0, num(d.get('k1', 0)), 0])
        for t in cal.findall('tca'):
            f, m = num(t.get('focal')), t.get('model')
            if m == 'poly3':
                T.append([f, num(t.get('vr', 1)), num(t.get('vb', 1)), num(t.get('cr', 0)), num(t.get('cb', 0)), num(t.get('br', 0)), num(t.get('bb', 0))])
            elif m == 'linear':
                T.append([f, num(t.get('kr', 1)), num(t.get('kb', 1)), 0, 0, 0, 0])
        for v in cal.findall('vignetting'):
            if v.get('model') != 'pa':
                continue
            key = (num(v.get('focal')), num(v.get('aperture')))
            dist = float(v.get('distance', 1000))
            if key not in V or dist > V[key][0]:
                V[key] = (dist, [key[0], key[1], num(v.get('k1', 0)), num(v.get('k2', 0)), num(v.get('k3', 0))])
        if not (D or T or V):
            continue
        lenses.append([mk[0], md, [m.text.strip() for m in l.findall('mount') if m.text],
                       num(l.findtext('cropfactor') or 1), num(l.findtext('aspect-ratio') or 1.5),
                       sorted(D), sorted(T), sorted(x[1] for x in V.values())])

# cameras: crop factor for all; the mount only matters for fixed-lens ones (a mount no <mount> element defines)
cams = [[mk, md, mt if mt not in mounts_defined else '', crop] for mk, md, mt, crop in cams]
body = json.dumps({'lenses': lenses, 'cams': cams}, ensure_ascii=False, separators=(',', ':')).encode()
b64 = base64.b64encode(zlib.compress(body, 9)).decode()
open('src/lensfun.js', 'w', encoding='utf-8', newline='\n').write(
    '// Generated by tools/make_lensfun.py from the lensfun database' + (f' (commit {commit[:7]})' if commit else '') + '.\n'
    '// Lens data: lensfun project, https://lensfun.github.io/ - licensed CC BY-SA 3.0 (this file too).\n'
    '// zlib-compressed JSON {lenses, cams} in base64 (inflated on first use, see lensfunDB() in app.js):\n'
    '// lenses: [maker, [names], [mounts], crop factor, aspect ratio, distortion [focal, a, b, c] (ptlens; poly3 as a=c=0),\n'
    '//   tca [focal, vr, vb, cr, cb, br, bb] (poly3), vignetting [focal, aperture, k1, k2, k3] (pa)]; cams: [maker, [models], fixed-lens mount or "", crop]\n'
    'const LENSFUN_Z = "' + b64 + '";\n')
print(len(lenses), 'lenses', len(cams), 'cameras', len(body) // 1024, 'KB JSON ->', os.path.getsize('src/lensfun.js') // 1024, 'KB')
