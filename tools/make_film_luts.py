"""Build src/filmluts.js from film-emulation LUT files.

usage: python tools/make_film_luts.py tools/film_luts.json
config: {"size": 33, "items": [{"id", "name", "d", "file", "type": "hald"|"cube"|"test", ...extra metadata}]}

Every LUT is resampled (trilinear) to size^3 as 8-bit RGB with red varying fastest, stored as the difference from the
identity LUT delta-coded along red (mod 256), concatenated, zlib-compressed and base64-encoded. The app inflates it with DecompressionStream('deflate') and uploads one 3D texture per LUT.
Inputs and outputs are display-referred sRGB (the usual convention for HaldCLUT / .cube film emulations).
"""
import base64, json, os, sys, zlib
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_hald(path):
    im = np.asarray(Image.open(path).convert('RGB'), dtype=np.float64) / 255.0
    w, h = im.shape[1], im.shape[0]
    n = round((w * h) ** (1 / 3))
    if n ** 3 != w * h:
        raise ValueError(f'{path}: {w}x{h} is not a HaldCLUT')
    return im.reshape(n, n, n, 3)  # [b][g][r]


def read_cube(path):
    size, rows, lo, hi = None, [], np.zeros(3), np.ones(3)
    for line in open(path, encoding='utf-8', errors='replace'):
        t = line.strip()
        if not t or t.startswith('#'):
            continue
        k = t.split()
        if k[0] == 'LUT_3D_SIZE':
            size = int(k[1])
        elif k[0] == 'DOMAIN_MIN':
            lo = np.array(list(map(float, k[1:4])))
        elif k[0] == 'DOMAIN_MAX':
            hi = np.array(list(map(float, k[1:4])))
        elif k[0][0] in '-.0123456789' and len(k) >= 3:
            rows.append(list(map(float, k[:3])))
    a = np.array(rows, dtype=np.float64)
    if size is None or a.shape[0] != size ** 3:
        raise ValueError(f'{path}: bad .cube ({a.shape[0]} rows, size {size})')
    if np.any(lo != 0) or np.any(hi != 1):
        raise ValueError(f'{path}: only DOMAIN 0..1 is supported')
    return a.reshape(size, size, size, 3)  # [b][g][r], red fastest


def test_lut(kind, n=17):
    g = np.linspace(0, 1, n)
    b, gg, r = np.meshgrid(g, g, g, indexing='ij')
    c = np.stack([r, gg, b], -1)
    if kind == 'warm':
        c = c ** np.array([0.9, 1.0, 1.15])
    return c


def resample(lut, size):
    n = lut.shape[0]
    x = np.linspace(0, n - 1, size)
    i0 = np.clip(np.floor(x).astype(int), 0, n - 2)
    f = x - i0
    B, G, R = np.meshgrid(np.arange(size), np.arange(size), np.arange(size), indexing='ij')
    b0, g0, r0 = i0[B], i0[G], i0[R]
    fb, fg, fr = f[B][..., None], f[G][..., None], f[R][..., None]
    out = 0
    for db in (0, 1):
        for dg in (0, 1):
            for dr in (0, 1):
                w = (fb if db else 1 - fb) * (fg if dg else 1 - fg) * (fr if dr else 1 - fr)
                out = out + w * lut[b0 + db, g0 + dg, r0 + dr]
    return out


def main(cfg_path):
    cfg = json.load(open(cfg_path, encoding='utf-8'))
    size = cfg.get('size', 33)
    base = os.path.dirname(os.path.abspath(cfg_path))
    blobs, meta = [], []
    for it in cfg['items']:
        t = it.get('type', 'hald')
        if t == 'test':
            lut = test_lut(it.get('kind', 'identity'))
        else:
            path = it['file'] if os.path.isabs(it['file']) else os.path.join(base, it['file'])
            lut = read_hald(path) if t == 'hald' else read_cube(path)
        q = np.clip(np.round(resample(lut, size) * 255), 0, 255).astype(np.int32)
        # store the difference from the identity LUT, then delta-code it along the red axis (both mod 256): film LUTs are
        # smooth, so this compresses several times better than raw values and decodes exactly (see loadFilmLUTs)
        ident = np.round(np.linspace(0, 255, size)).astype(np.int32)
        B, G, R = np.meshgrid(ident, ident, ident, indexing='ij')
        d = (q - np.stack([R, G, B], -1)) % 256
        d = np.concatenate([d[:, :, :1], np.diff(d, axis=2)], axis=2) % 256
        blobs.append(d.astype(np.uint8).tobytes())
        meta.append({k: v for k, v in it.items() if k not in ('file', 'type', 'kind')})
    data = base64.b64encode(zlib.compress(b''.join(blobs), 9)).decode()
    out = os.path.join(ROOT, 'src', 'filmluts.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/make_film_luts.py. Film emulation LUT DATA - NOT covered by the project MIT licence.\n')
        f.write('// Adapted from the RawTherapee Film Simulation Collection (Pat David, Pavlov Dmitry, Michael Ezra; CC BY-SA 4.0),\n')
        f.write('// t3mujinpack (Joao Almeida; MIT) and FilmSim (Sebastien Guyader; CC0). Resampled to 33^3. See FILM_LUTS.md.\n')
        f.write('const FILM_LUTS = { size: %d, list: %s,\n  data: "%s" };\n' % (size, json.dumps(meta, ensure_ascii=False), data))
    print(f'{len(meta)} LUTs, {size}^3, {len(data) / 1024:.0f} KB base64 -> {out}')


if __name__ == '__main__':
    main(sys.argv[1])
